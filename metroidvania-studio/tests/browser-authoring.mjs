import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const base = process.env.METROIDVANIA_STUDIO_BASE_URL;
assert.equal(process.env.METROIDVANIA_STUDIO_TEST_ISOLATED, '1');
const browser = await chromium.launch({ channel: process.env.METROIDVANIA_STUDIO_BROWSER_CHANNEL || (process.platform === 'win32' ? 'msedge' : undefined), headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'en-US' });
page.setDefaultTimeout(15000);
const errors = []; page.on('pageerror', e => errors.push(e.message));
const get = async url => { const r = await fetch(base + url); assert.equal(r.status, 200); return r.json(); };
const post = (body, raw = false) => fetch(base + '/api/v1/scripts', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: raw ? body : JSON.stringify(body) });
try {
  const before = await get('/api/v1/document');
  let response = await post({ name: 'library-한글.lua', source: 'print("hello")', expectedRevision: null }); assert.equal(response.status, 200);
  const original = await response.json();
  assert.equal((await get('/api/v1/scripts/source?id=workspace%2Flibrary-%ED%95%9C%EA%B8%80.lua')).source, 'print("hello")');
  assert.equal((await post({ name: original.name, source: 'overwrite', expectedRevision: null })).status, 409);
  response = await post({ name: original.name, source: 'print("updated")', expectedRevision: original.revision }); assert.equal(response.status, 200);
  assert.equal((await post({ name: original.name, source: 'stale', expectedRevision: original.revision })).status, 409);
  for (const name of ['../escape.lua', '/escape.lua', 'CON.lua', 'a\\escape.lua']) assert.equal((await post({ name, source: 'print(1)', expectedRevision: null })).status, 400);
  assert.equal((await post({ name: 'large.lua', source: '가'.repeat(22000), expectedRevision: null })).status, 400);
  assert.equal((await post({ name: 'missing.lua', source: 'print(1)' })).status, 400);
  assert.equal((await post('{"name":"a.lua","source":"print(1)","expectedRevision":null,"source":"print(2)"}', true)).status, 400);
  assert.deepEqual((await get('/api/v1/document')), before, 'Library operations must not change the active map.');
  await page.goto(base); await page.locator('#room-list button').first().waitFor();
  await page.locator('#file-menu-button').click(); await page.locator('#scripts-action').click();
  await page.waitForFunction(() => document.querySelector('#script-library option[value="examples/connected-rooms.lua"]'));
  await page.locator('#script-library').selectOption('examples/connected-rooms.lua');
  await page.waitForFunction(() => document.querySelector('#script-output').textContent.includes('Script opened'));
  assert.deepEqual((await get('/api/v1/document')).document, before.document, 'Opening an example must not run it.');
  await page.locator('#script-source').fill('print("saved from the UI")');
  await page.locator('#script-name').fill('ui-example.lua'); await page.locator('#script-save-library').click();
  await page.waitForFunction(() => document.querySelector('#script-output').textContent.includes('Saved in'));
  assert.equal((await get('/api/v1/scripts/source?id=workspace%2Fui-example.lua')).source, 'print("saved from the UI")');
  await page.locator('#script-run').click(); await page.waitForFunction(() => document.querySelector('#script-output').textContent.includes('saved from the UI'));
  const screenshots = path.join(root, '.local/authoring-1.2'); await mkdir(screenshots, { recursive: true });
  await page.screenshot({ path: path.join(screenshots, 'script-library.png') });
  await page.keyboard.press('Escape'); await page.locator('#script-dialog').waitFor({ state: 'detached' });
  const popup = page.waitForEvent('popup'); await page.locator('#help-menu-button').click(); await page.getByRole('menuitem', { name: 'API reference', exact: true }).click();
  const docs = await popup; await docs.waitForLoadState();
  assert.ok((await docs.title()).includes('Metroidvania Studio'));
  await docs.locator('#search').fill('headless'); await docs.locator('#results a').first().waitFor();
  await docs.locator('#results a[href="cli--release-downloads.html"]').click();
  await docs.getByRole('heading', { name: 'Headless from a release download', exact: true }).waitFor();
  await docs.screenshot({ path: path.join(screenshots, 'api-reference.png') });
  await docs.setViewportSize({ width: 390, height: 844 });
  assert.equal(await docs.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Documentation should fit a small window.');
  await docs.close();
  const offline = await browser.newPage();
  await offline.goto(pathToFileURL(path.join(process.env.METROIDVANIA_STUDIO_TEST_WEB_ROOT, 'docs/index.html')).href);
  await offline.locator('#search').fill('studio.tiles'); await offline.locator('#results a').first().waitFor();
  await offline.close();
  assert.equal((await fetch(base + '/docs/%2e%2e%2fversion.json')).status, 404);
  assert.equal((await fetch(base + '/api/v1/scripts', { method: 'POST', headers: { Origin: 'https://invalid.example', 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  assert.deepEqual(errors, []);
  console.log('Script library, save conflicts, explicit execution, documentation navigation/search and offline pages passed.');
} finally { await browser.close(); }
